// quiz question generator helpers ------------------------------------------------
const quizRows = [];

function shuffleArr(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

// `options[0]` is always the correct choice at the call site (by convention across
// this whole file); we shuffle the four choices here so the correct answer doesn't
// always land in the same slot, and compute which key ('a'-'d') it ended up at.
function addQuiz(type, level, prompt, audio_text, options, _answerIgnored, explanation) {
  const correctText = options[0];
  const shuffled = shuffleArr(options);
  const keys = ['a', 'b', 'c', 'd'];
  const answerKey = keys[shuffled.indexOf(correctText)];
  const [a, b, c, d] = shuffled;
  quizRows.push([type, level, prompt, audio_text, a, b, c, d, answerKey, explanation || null]);
}

