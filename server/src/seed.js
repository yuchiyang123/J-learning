function pickDistractors(pool, excludeMeaning, n) {
  const seen = new Set([excludeMeaning]);
  const out = [];
  for (const w of shuffleArr(pool)) {
    const meaning = w[3];
    if (seen.has(meaning)) continue;
    seen.add(meaning);
    out.push(meaning);
    if (out.length === n) break;
  }
  return out;
}

const VOCAB_MEANING_PER_LEVEL = 300;
const VOCAB_READING_PER_LEVEL = 150;
const LISTENING_PER_LEVEL = 150;

// The bulk listening quiz can't show the tested word as text (that would
// give the audio question away), so every one of these ~150-per-level
// questions used to share one literal instruction string verbatim — scanning
// a list of them reads as broken/duplicated content even though each one
// plays different audio. Cycling a few natural equivalent phrasings keeps
// consecutive questions from being byte-identical without hinting the answer.
const LISTENING_WORD_PROMPTS = [
  '聞こえた単語の意味を選んでください。',
  '音声を聞いて、正しい意味を選んでください。',
  'この単語の意味は何ですか？音声を聞いて選んでください。',
  '聞こえた単語はどんな意味ですか？',
];

for (const level of ['N5', 'N4', 'N3', 'N2', 'N1']) {
  const pool = wordsByLevel[level] || [];
  if (pool.length < 4) continue;

  // meaning quiz: 「word」の意味は？
  for (const w of shuffleArr(pool).slice(0, VOCAB_MEANING_PER_LEVEL)) {
    const [, kanjiField, kana, meaning] = w;
    const display = kanjiField || kana;
    const distractors = pickDistractors(pool, meaning, 3);
    if (distractors.length < 3) continue;
    addQuiz('vocab', level, `「${display}」の意味は？`, null, [meaning, ...distractors], 'a', `${display}＝${kana}＝${meaning}`);
  }

  // reading quiz: 「word」の読み方は？ (only for words that actually have kanji)
  const withKanji = pool.filter((w) => w[1]);
  for (const w of shuffleArr(withKanji).slice(0, VOCAB_READING_PER_LEVEL)) {
    const [, kanjiField, kana, meaning] = w;
    const distractorReadings = shuffleArr(withKanji.filter((x) => x[2] !== kana)).slice(0, 3).map((x) => x[2]);
    if (distractorReadings.length < 3) continue;
    addQuiz('vocab', level, `「${kanjiField}」の読み方は？`, null, [kana, ...distractorReadings], 'a', `${kanjiField}＝${kana}＝${meaning}`);
  }

  // listening quiz: audio_text spoken aloud, choose the meaning
  let listeningIndex = 0;
  for (const w of shuffleArr(pool).slice(0, LISTENING_PER_LEVEL)) {
    const [, , kana, meaning] = w;
    const distractors = pickDistractors(pool, meaning, 3);
    if (distractors.length < 3) continue;
    const prompt = LISTENING_WORD_PROMPTS[listeningIndex % LISTENING_WORD_PROMPTS.length];
    listeningIndex++;
    addQuiz('listening', level, prompt, kana, [meaning, ...distractors], 'a');
  }
}

// kanji quiz: one meaning question + one reading question per kanji entry.
// Distractors are drawn from the full kanji list (not just the same level) so
// sparsely-populated levels still get enough choices.
for (const k of allKanji) {
  const [level, character, onyomi, kunyomi, meaning] = k;

  const meaningDistractors = shuffleArr(allKanji.filter((x) => x[4] !== meaning && x[1] !== character))
    .slice(0, 3)
    .map((x) => x[4]);
  if (meaningDistractors.length === 3) {
    addQuiz('kanji', level, `「${character}」の意味は？`, null, [meaning, ...meaningDistractors], 'a', `${character}＝${meaning}`);
  }

  const firstReading = (str) => (str && str !== '-' ? str.split('、')[0].replace(/-.*/, '') : '');
  const reading = firstReading(kunyomi) || firstReading(onyomi);
  if (reading) {
    const readingDistractors = shuffleArr(allKanji.filter((x) => x[1] !== character))
      .map((x) => firstReading(x[3]) || firstReading(x[2]))
      .filter((r) => r && r !== reading);
    const uniqueDistractors = [...new Set(readingDistractors)].slice(0, 3);
    if (uniqueDistractors.length === 3) {
      addQuiz('kanji', level, `「${character}」の読み方は？`, null, [reading, ...uniqueDistractors], 'a', `${character}＝${reading}`);
    }
  }
}

// grammar quiz: one meaning-matching question per grammar point
const grammarByLevel = {};
for (const g of grammar) (grammarByLevel[g[0]] ??= []).push(g);

for (const g of grammar) {
  const [level, pattern, meaning] = g;
  const pool = grammarByLevel[level] || [];
  const distractors = shuffleArr(pool.filter((x) => x[1] !== pattern)).slice(0, 3).map((x) => x[2]);
  if (distractors.length === 3) {
    addQuiz('grammar', level, `「${pattern}」の意味は？`, null, [meaning, ...distractors], 'a', `${pattern}＝${meaning}`);
  }
}

// JLPT mock exam questions reuse the level tagging above (mixed types) so no extra table needed.

function run() {
  const insertWord = db.prepare(`INSERT INTO words (level, kanji, kana, meaning, part_of_speech, example_jp, example_reading, example_zh) VALUES (?,?,?,?,?,?,?,?)`);
  const insertKanji = db.prepare(`INSERT INTO kanji (level, character, onyomi, kunyomi, meaning, stroke_count) VALUES (?,?,?,?,?,?)`);
  const insertGrammar = db.prepare(`INSERT INTO grammar_points (level, pattern, meaning, explanation, example_jp, example_reading, example_zh) VALUES (?,?,?,?,?,?,?)`);
  const insertQuiz = db.prepare(`INSERT INTO quiz_questions (type, level, prompt, audio_text, option_a, option_b, option_c, option_d, answer, explanation) VALUES (?,?,?,?,?,?,?,?,?,?)`);

  const clear = db.transaction(() => {
    db.exec('DELETE FROM words; DELETE FROM kanji; DELETE FROM grammar_points; DELETE FROM quiz_questions;');
  });
  clear();

  const insertAll = db.transaction(() => {
    for (const w of words) insertWord.run(...w);
    for (const w of bulkWords) insertWord.run(...w);
    for (const k of allKanji) insertKanji.run(...k);
    for (const g of grammar) insertGrammar.run(...g);
    for (const q of quizRows) insertQuiz.run(...q);
  });
  insertAll();

  const totalWords = words.length + bulkWords.length;
  console.log(`Seeded ${totalWords} words (${words.length} curated + ${bulkWords.length} bulk JLPT list), ${allKanji.length} kanji (${kanji.length} curated + ${bulkKanji.length} bulk JLPT list), ${grammar.length} grammar points, ${quizRows.length} quiz questions.`);
}

